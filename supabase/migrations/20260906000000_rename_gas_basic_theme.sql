--
-- 背景（#166）: 20260412010002_seed_gas_course_structure.sql が作成する
-- 基礎コースのテーマ名は 'GAS学習' だが、本番では 'GAS学習（基礎編）' に
-- リネームされている（マイグレーション上は未記録のUPDATE）。この差異を解消する。
--
