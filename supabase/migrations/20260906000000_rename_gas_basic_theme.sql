-- 使わず、通常どおりのタイムスタンプで `db push` の通常経路に乗せる。
--
-- 本番への反映時: 既に手動でリネーム済みのため、通常の `db push` を実行すれば
-- 対象行が無く何も変更されない（無害な no-op）。他の #166 以前に本番へ手動反映済みの
-- マイグレーション（docs/database.md 7.1節参照）と同様に、
-- `supabase migration repair --status applied 20260906000000` で
-- 適用済みとして記録してもよい。
-- =====================================================

